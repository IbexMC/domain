    private int placedID;
    private Type flagType;
    private boolean active;
    private Timestamp setDateTime;
    private String setBy;


    public Flag() {

    }
    public Flag(int placedID, Flag.Type type, boolean active) {
        if (type == null) {
            return;
        }
        this.placedID = placedID;
        this.flagType = type;
        this.active = active;
    }
    public Flag(int placedID, Flag.Type type, boolean active, String setBy) {
        this.placedID = placedID;
        this.flagType = type;
        this.active = active;
        this.setBy = setBy;
        this.setDateTime = new Timestamp(System.currentTimeMillis());
    }
    public Flag(int placedID, Flag.Type type, boolean active, String setBy, Timestamp setDateTime) {
        this.placedID = placedID;
        this.flagType = type;
        this.active = active;
        this.setBy = setBy;
        this.setDateTime = setDateTime;
    }

    public int getPlacedID() {
        return this.placedID;
    }
    public Type getFlagType() {
        return this.flagType;
    }
    public boolean isActive() {
        //Logging.dev("Flag", "isActive", "Flag: " + this.flagType.name() + " Status: " + Boolean.toString(this.active));
        return this.active;
    }
    public Timestamp getSetDateTime() {
        return this.setDateTime;
    }
    public String getSetBy() {
        return this.setBy;
    }

    /**
     * Gets the flag type by name
     * @param flagName Flag name to lookup
     * @return Flag.Type, if not found, returns null
     */
    public static Flag.Type flagFromString(String flagName) {
        for (Flag.Type type : Flag.Type.values()) {
            if (type.name().equalsIgnoreCase(flagName)) {
                return type;
            }
        }
        return null;
    }
